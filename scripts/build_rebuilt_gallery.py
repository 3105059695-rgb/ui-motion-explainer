"""Build the fetch-free independent scene gallery; media stays in shared assets."""
from pathlib import Path
import hashlib,json

ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'assets/rebuilt-library'
def build(root=ROOT):
 root=Path(root);base=root/'assets/rebuilt-library';items=[]
 for path in sorted((base/'scenes').glob('*.json')):
  scene=json.loads(path.read_text(encoding='utf-8-sig'))
  for rel in scene.get('extensions',[]):
   extension=(base/rel).resolve()
   if not extension.is_relative_to(base.resolve()) or not extension.is_file():raise ValueError('Missing/outside extension: '+rel)
  for rel in scene.get('assets',{}).values():
   media=(root/rel).resolve()
   if not media.is_relative_to(root.resolve()) or not media.is_file():raise ValueError('Missing/outside demo asset: '+rel)
  items.append({'id':scene['id'],'title':scene['title'],'duration':scene['duration'],'scene_file':path.relative_to(root).as_posix(),'scene_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'scene':scene})
 if len({item['id']for item in items})!=len(items):raise ValueError('Duplicate gallery ID')
 data={'schema':'ui-motion-fusion/independent-gallery@1','count':len(items),'user_approved':False,'items':items}
 text='/* Generated by scripts/build_rebuilt_gallery.py. No fetch or local resource map. */\nwindow.RebuiltGalleryData='+json.dumps(data,ensure_ascii=False,separators=(',',':')).replace('<','\\u003c')+';\n'
 (base/'gallery-data.js').write_text(text,encoding='utf-8')
 return {'entries':len(items),'bytes':len(text.encode('utf-8')),'output':str(base/'gallery-data.js')}
if __name__=='__main__':print(json.dumps(build(),ensure_ascii=False))
