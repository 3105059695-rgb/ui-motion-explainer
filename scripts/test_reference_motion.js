'use strict';
const assert=require('node:assert/strict');
const R=require('../assets/reference-films/arun-membership/reference-scene.js');
const timelineEvent=[{id:'change',start:1,end:5}];
assert.equal(R.eventProgress(1,timelineEvent,'change'),0);
assert(R.eventProgress(2,timelineEvent,'change')<1,'Canvas start/end must not finish at the default duration');
assert.equal(R.eventProgress(5,timelineEvent,'change'),1);
assert.equal(R.eventProgress(2,[{id:'change',start:1,end:5,duration:1}],'change'),1,'Explicit duration remains authoritative');
assert.throws(()=>R.eventProgress(2,[{id:'change',start:1,end:1}],'change'),/Invalid motion event/);
assert.throws(()=>R.eventProgress(2,[{id:'change',start:1,end:'5'}],'change'),/Invalid motion event/);
const objects=[{id:'text'},{id:'image'},{id:'task'}];
const spec={kind:'independent',objects,focus:2};
assert.deepEqual(R.stateAt(spec,0).items.map(i=>i.amount),[1,1,1]);
assert.deepEqual(R.stateAt(spec,4).items.map(i=>i.amount),[1,1,0]);
const blocked={kind:'blocked',toAmount:.43};
assert.equal(R.stateAt(blocked,3).amount,.43);
assert.equal(R.stateAt(blocked,8).amount,.43);
assert.equal(R.stateAt({kind:'blackbox'},1).open,0);
assert(R.stateAt({kind:'blackbox'},3).open>.999);
const evidence={kind:'evidence',objects,events:[{id:'return',at:3,duration:.5}]};
assert.equal(R.stateAt(evidence,5).focusProgress,0);
const first=R.stateAt(evidence,2);R.stateAt(evidence,5);assert.deepEqual(first,R.stateAt(evidence,2));
const decisions=R.stateAt({kind:'decision',objects},.4);
assert(decisions.items[0].answer>0);assert.equal(decisions.items[1].answer,0);
assert.throws(()=>R.stateAt({kind:'unknown'},0),/Unknown/);
assert.throws(()=>R.stateAt({kind:'objects',objects:[{id:'same'},{id:'same'}]},0),/unique/);
assert.equal(typeof R.createScene({kind:'objects',objects}),'function');
console.log('Reference mechanisms: deterministic states, evidence return, independent quota, blocked hold and delayed answers passed.');
